const configFileName = "dotgithub.yml"

// exit codes.
const (
	ExitOK                       = 0
	ExitLintErrors               = 1
	ExitLintOnlyWarnings         = 2
	ExitErrLinting               = 10
	ExitErrReadingDotGithubDir   = 20
	ExitErrGettingCfgFile        = 30
	ExitErrReadingCfgFile        = 31
	ExitErrReadingDefaultCfgFile = 32
	ExitErrGettingLinter         = 33
	ExitErrGettingDotGithub      = 34
	ExitErrReadingVarsFile       = 41
	ExitErrReadingSecretsFile    = 42
	ExitErrCheckingDstPath       = 50
	ExitDstFileIsDir             = 51
	ExitErrWritingCfg            = 52
)

const (
	// FileModeDefaultConfig sets the mode for the config file generated by the 'init' command.
	FileModeDefaultConfig = 0o600
)

var (
	errCfgFileGet               = errors.New("error getting cfg file")
	errCfgFilePopulate          = errors.New("error populating config from file")
	errCfgFileRead              = errors.New("error reading cfg file")
	errDefaultCfgFileRead       = errors.New("error reading default cfg file")
	errDotGithubDirRead         = errors.New("error reading .github directory")
	errDotGithubVarsFileRead    = errors.New("error reading vars file")
	errDotGithubSecretsFileRead = errors.New("error reading secrets file")
)

func errGettingCfgFile(err error) error {
	return fmt.Errorf("%w: %s", errCfgFileGet, err.Error())
}

func errPopulatingCfgFile(err error) error {
	return fmt.Errorf("%w: %s", errCfgFilePopulate, err.Error())
}

func errReadingCfgFile(err error) error {
	return fmt.Errorf("%w: %s", errCfgFileRead, err.Error())
}

func errReadingDefaultCfgFile(err error) error {
	return fmt.Errorf("%w: %s", errDefaultCfgFileRead, err.Error())
}

func errReadingDotGithubDir(err error) error {
	return fmt.Errorf("%w: %s", errDotGithubDirRead, err.Error())
}

func errReadingDotGithubVarsFile(err error) error {
	return fmt.Errorf("%w: %s", errDotGithubVarsFileRead, err.Error())
}

func errReadingDotGithubSecretsFile(err error) error {
	return fmt.Errorf("%w: %s", errDotGithubSecretsFileRead, err.Error())
}

func main() {
	//nolint:exhaustruct
	rootCmd := &cobra.Command{
		Use:   "octo-linter",
		Short: "Validates GitHub Actions workflow and action YAML files",
	}

	rootCmd.AddCommand(createInitCommand())
	rootCmd.AddCommand(createLintCommand())
	//nolint:exhaustruct
	rootCmd.AddCommand(&cobra.Command{
		Use:   "version",
		Short: "Prints the current version of the tool",
		Run: func(_ *cobra.Command, _ []string) {
			os.Exit(versionHandler(context.Background()))
		},
	})

	err := rootCmd.Execute()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func createLintCommand() *cobra.Command {
	var (
		path, config, loglevel, varsFile, secretsFile, output string
		logmultiline                                          bool
		outputErrors                                          int
	)

	//nolint:exhaustruct
	cmd := &cobra.Command{
		Use:   "lint",
		Short: "Runs the linter on files from a specific directory",
		Run: func(cmd *cobra.Command, _ []string) {
			setLogger(loglevel, logmultiline)

			ctx := cmd.Context()

			cleanPath := filepath.Clean(path)
			if _, err := os.Stat(cleanPath); err != nil {
				if os.IsNotExist(err) {
					slog.Error("path does not exist", slog.String("path", path))
					os.Exit(ExitErrReadingDotGithubDir)
				}

				slog.Error(
					"error accessing path",
					slog.String("path", path),
					slog.String("err", err.Error()),
				)
				os.Exit(ExitErrReadingDotGithubDir)
			}

			if config != "" {
				config = filepath.Clean(config)
				if _, err := os.Stat(config); err != nil {
					if os.IsNotExist(err) {
						slog.ErrorContext(
							ctx,
							"config file does not exist",
							slog.String("config", config),
						)
						os.Exit(ExitErrGettingCfgFile)
					}

					slog.ErrorContext(
						ctx,
						"error accessing config",
						slog.String("config", config),
						slog.String("err", err.Error()),
					)
					os.Exit(ExitErrGettingCfgFile)
				}
			}

			if varsFile != "" {
				varsFile = filepath.Clean(varsFile)
				if _, err := os.Stat(varsFile); err != nil {
					if os.IsNotExist(err) {
						slog.ErrorContext(
							ctx,
							"vars file does not exist",
							slog.String("vars_file", varsFile),
						)
						os.Exit(ExitErrReadingVarsFile)
					}

					slog.ErrorContext(
						ctx,
						"error accessing vars file",
						slog.String("vars_file", varsFile),
						slog.String("err", err.Error()),
					)
					os.Exit(ExitErrReadingVarsFile)
				}
			}

			if secretsFile != "" {
				secretsFile = filepath.Clean(secretsFile)
				if _, err := os.Stat(secretsFile); err != nil {
					if os.IsNotExist(err) {
						slog.ErrorContext(
							ctx,
							"secrets file does not exist",
							slog.String("secrets_file", secretsFile),
						)
						os.Exit(ExitErrReadingSecretsFile)
					}

					slog.ErrorContext(
						ctx,
						"error accessing secrets file",
						slog.String("secrets_file", secretsFile),
						slog.String("err", err.Error()),
					)
					os.Exit(ExitErrReadingSecretsFile)
				}
			}

			if output != "" {
				output = filepath.Clean(output)

				fileInfo, err := os.Stat(output)
				if err != nil {
					if os.IsNotExist(err) {
						slog.ErrorContext(
							ctx,
							"output path does not exist",
							slog.String("output", output),
						)
						os.Exit(ExitErrCheckingDstPath)
					}

					slog.ErrorContext(
						ctx,
						"error accessing output file",
						slog.String("output", output),
						slog.String("err", err.Error()),
					)
					os.Exit(ExitErrCheckingDstPath)
				}

				if !fileInfo.IsDir() {
					slog.Error("output is not a directory", slog.String("output", output))
					os.Exit(ExitDstFileIsDir)
				}
			}

			os.Exit(
				lintHandler(
					cmd.Context(),
					cleanPath,
					config,
					varsFile,
					secretsFile,
					output,
					outputErrors,
				),
			)
		},
	}

	cmd.Flags().StringVarP(&path, "path", "p", "", "Path to .github directory (required)")
	_ = cmd.MarkFlagRequired("path")
	cmd.Flags().StringVarP(&config, "config", "c", "", "Linter config with rules in YAML format")
	cmd.Flags().StringVarP(&loglevel, "loglevel", "l", "", "One of INFO, ERR, WARN, DEBUG")
	cmd.Flags().
		BoolVarP(&logmultiline, "logmultiline", "m", false, "Each log entry key in a separate line")
	cmd.Flags().
		StringVarP(&varsFile, "vars-file", "z", "", "Check if variable names exist in this file (one per line)")
	cmd.Flags().
		StringVarP(&secretsFile, "secrets-file", "s", "", "Check if secret names exist in this file (one per line)")
	cmd.Flags().
		StringVarP(&output, "output", "o", "", "Path to where summary markdown gets generated")
	cmd.Flags().
		IntVarP(&outputErrors, "output-errors", "u", 0, "Limit numbers of errors shown in the markdown output file")

	return cmd
}

func createInitCommand() *cobra.Command {
	var destination string

	//nolint:exhaustruct
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Create sample dotgithub.yml config file",
		Run: func(cmd *cobra.Command, _ []string) {
			cleanDestination := filepath.Clean(destination)
			os.Exit(initHandler(cmd.Context(), cleanDestination))
		},
	}

	cmd.Flags().StringVarP(&destination, "destination", "d", "", "Destination filename to write to")

	return cmd
}

func versionHandler(_ context.Context) int {
	_, _ = fmt.Fprintf(os.Stdout, VERSION+"\n")

	return ExitOK
}

func initHandler(ctx context.Context, path string) int {
	if path == "" {
		cleanConfigFileName := filepath.Clean(configFileName)

		fileInfo, err := os.Stat(cleanConfigFileName)
		if err != nil && !os.IsNotExist(err) {
			slog.ErrorContext(
				ctx,
				"error checking if destination path exists",
				slog.String("destination", configFileName),
				slog.String("err", err.Error()),
			)

			return ExitErrCheckingDstPath
		}

		if err == nil {
			if fileInfo.IsDir() {
				slog.ErrorContext(
					ctx,
					"destination file already exists and it is a directory, remove it first or use --destination flag to change"+
						" the destination",
					slog.String("destination", configFileName),
				)

				return ExitDstFileIsDir
			}

			slog.WarnContext(ctx, "config file already exists, it will be overwritten")
		}

		path = configFileName
	}

	err := os.WriteFile(path, linter.GetDefaultConfig(), FileModeDefaultConfig)
	if err != nil {
		slog.ErrorContext(
			ctx,
			"error writing default config",
			slog.String("path", path),
			slog.String("err", err.Error()),
		)

		return ExitErrWritingCfg
	}

	slog.InfoContext(
		ctx,
		"Sample configuration file has been created. Run 'lint' command with '-c' flag or put the file in the .github"+
			" directory.",
		slog.String("path", path),
	)

	return ExitOK
}

func lintHandler(
	ctx context.Context,
	path, config, varsFile, secretsFile, output string,
	outputErrors int,
) int {
	lint, err := getLinter(config, path)
	if err != nil {
		return errorToExitCode(err)
	}

	dotGithub, err := getDotGithub(ctx, path, varsFile, secretsFile, lint.Config.Overrides)
	if err != nil {
		return errorToExitCode(err)
	}

	outputLimit := max(outputErrors, 0)

	status, err := lint.Lint(dotGithub, output, outputLimit)
	if err != nil {
		slog.ErrorContext(ctx, "error linting", slog.String("err", err.Error()))

		return ExitErrLinting
	}

	switch status {
	case linter.HasErrors:
		return ExitLintErrors
	case linter.HasOnlyWarnings:
		return ExitLintOnlyWarnings
	default:
		return 0
	}
}

func errorToExitCode(err error) int {
	if errors.Is(err, errCfgFileGet) {
		return ExitErrGettingCfgFile
	}

	if errors.Is(err, errCfgFileRead) {
		return ExitErrReadingCfgFile
	}

	if errors.Is(err, errDefaultCfgFileRead) {
		return ExitErrReadingDefaultCfgFile
	}

	if errors.Is(err, errDotGithubDirRead) {
		return ExitErrReadingDotGithubDir
	}

	if errors.Is(err, errDotGithubVarsFileRead) {
		return ExitErrReadingVarsFile
	}

	if errors.Is(err, errDotGithubSecretsFileRead) {
		return ExitErrReadingSecretsFile
	}

	return ExitErrLinting
}

func getConfigFilePath(filePath string, dotGitHubPath string) (string, error) {
	if filePath != "" {
		return filePath, nil
	}

	configInDotGithub := filepath.Clean(filepath.Join(dotGitHubPath, configFileName))
	_, err := os.Stat(configInDotGithub)

	notFound := os.IsNotExist(err)
	if err != nil && !notFound {
		slog.Error(
			"error getting config file",
			slog.String("err", err.Error()),
		)

		return "", fmt.Errorf(
			"error getting os.Stat on %s inside .github path: %w",
			configFileName,
			err,
		)
	}

	if notFound {
		return "", nil
	}

	return configInDotGithub, nil
}

func populateConfigFromFile(cfg *linter.Config, cfgFile string) error {
	if cfgFile != "" {
		err := cfg.ReadFile(cfgFile)
		if err != nil {
			slog.Error(
				"error reading config file",
				slog.String("path", cfgFile),
				slog.String("err", err.Error()),
			)

			return errReadingCfgFile(err)
		}
	} else {
		err := cfg.ReadDefaultFile()
		if err != nil {
			slog.Error(
				"error reading default config file",
				slog.String("err", err.Error()),
			)

			return errReadingDefaultCfgFile(err)
		}
	}

	return nil
}

func getLinter(cfgPath string, dotGithubPath string) (*linter.Linter, error) {
	cfgFile, err := getConfigFilePath(cfgPath, dotGithubPath)
	if err != nil {
		return nil, errGettingCfgFile(err)
	}

	//nolint:exhaustruct
	configInstance := linter.Config{}

	err = populateConfigFromFile(&configInstance, cfgFile)
	if err != nil {
		return nil, errPopulatingCfgFile(err)
	}

	linterInstance := &linter.Linter{
		Config: &configInstance,
	}

	return linterInstance, nil
}

func getDotGithub(
	ctx context.Context,
	dotGithubPath string,
	varsFile string,
	secretsFile string,
	overrides *linter.Overrides,
) (*dotgithub.DotGithub, error) {
	dotGithub := dotgithub.DotGithub{
		Actions:         map[string]*action.Action{},
		ExternalActions: map[string]*action.Action{},
		Workflows:       map[string]*workflow.Workflow{},
		Vars:            map[string]bool{},
		Secrets:         map[string]bool{},
	}

	overridePaths := map[string]string{}
	overrideOutputs := map[string][]*regexp.Regexp{}

	if overrides != nil {
		if len(overrides.ExternalActionsPaths) > 0 {
			maps.Copy(overridePaths, overrides.ExternalActionsPaths)
		}

		if len(overrides.ExternalActionsOutputs) > 0 {
			overrideOutputs = overrides.ExternalActionsOutputs
		}
	}

	err := dotGithub.ReadDir(ctx, dotGithubPath, overridePaths, overrideOutputs)
	if err != nil {
		slog.ErrorContext(
			ctx,
			"error initializing",
			slog.String("path", dotGithubPath),
			slog.String("err", err.Error()),
		)

		return nil, errReadingDotGithubDir(err)
	}

	if varsFile != "" {
		err = dotGithub.ReadVars(varsFile)
		if err != nil {
			slog.ErrorContext(
				ctx,
				"error reading vars file",
				slog.String("path", varsFile),
				slog.String("err", err.Error()),
			)

			return nil, errReadingDotGithubVarsFile(err)
		}
	}

	if secretsFile != "" {
		err = dotGithub.ReadSecrets(secretsFile)
		if err != nil {
			slog.ErrorContext(
				ctx,
				"error reading secrets file",
				slog.String("path", secretsFile),
				slog.String("err", err.Error()),
			)

			return nil, errReadingDotGithubSecretsFile(err)
		}
	}

	return &dotGithub, nil
}

func setLogger(loglevelFlag string, multiline bool) {
	logLevel := loglevel.GetLogLevelFromString(loglevelFlag)

	//nolint:exhaustruct
	opts := &slog.HandlerOptions{
		Level: logLevel,
		ReplaceAttr: func(groups []string, a slog.Attr) slog.Attr {
			if a.Key == slog.TimeKey {
				//nolint:exhaustruct
				return slog.Attr{}
			}

			if len(groups) > 0 {
				a.Key = strings.Join(groups, ".") + "." + a.Key
			}

			return a
		},
	}

	var logger *slog.Logger
	if multiline {
		//nolint:exhaustruct
		logger = slog.New(&customHandler{opts: opts, w: os.Stderr})
	} else {
		logger = slog.New(slog.NewTextHandler(os.Stderr, opts))
	}

	slog.SetDefault(logger)
}
